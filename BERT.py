class BERTEmbedding(nn.Module):
    # hidden_size=768 (Makaledeki BERT-Base'in uzay boyutu)
    def __init__(self, vocab_size, max_len=32, hidden_size=768):
        super().__init__()

        # 1. Kelimelerin kendi anlamları (padding_idx=0 diyerek [PAD] token'ını boş bırakıyoruz)
        self.token_emb = nn.Embedding(vocab_size, hidden_size, padding_idx=0)

        # 2. Pozisyon (Sıra) vektörleri
        self.position_emb = nn.Embedding(max_len, hidden_size)

        # 3. Segment (Cümle) vektörleri (0 veya 1 olacağı için toplam 2 tür)
        self.segment_emb = nn.Embedding(2, hidden_size)

        # Normalizasyon (LayerNorm) ve Ezber önleyici (Dropout)
        self.norm = nn.LayerNorm(hidden_size)
        self.dropout = nn.Dropout(0.1)

    def forward(self, input_ids, segment_ids):
        # input_ids boyutu: [batch_size, max_len] -> (Bizim örnekte [16, 32])
        seq_length = input_ids.size(1)

        # 0'dan 31'e kadar pozisyon ID'leri üretiyoruz (Cümledeki sırayı bilmesi için)
        position_ids = torch.arange(seq_length, dtype=torch.long, device=input_ids.device)
        position_ids = position_ids.unsqueeze(0).expand_as(input_ids)

        # 3 Farklı Embedding katmanından geçiriyoruz
        tokens = self.token_emb(input_ids)
        positions = self.position_emb(position_ids)
        segments = self.segment_emb(segment_ids)

        # MAKALEDEKİ O MEŞHUR "TOPLAMA" (SUMMING) İŞLEMİ
        x = tokens + positions + segments

        # Vektörü ehlileştir (Normalize et) ve dışarı yolla
        return self.dropout(self.norm(x))

