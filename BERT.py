# ==========================================
# ADIM 7: FeedForward (Öğrenme Katmanı)
# ==========================================
# Attention'dan çıkan karmaşık bilgiyi kalıcı hafızaya kazıyan düz katman.
class FeedForward(nn.Module):
    def __init__(self, hidden_size=768, ff_hidden_size=3072):
        super().__init__()
        # 768 boyutunu alıp 4 katına (3072) genişletir (BERT makalesi kuralı)
        self.linear1 = nn.Linear(hidden_size, ff_hidden_size)
        self.gelu = nn.GELU() # ReLU yerine GELU kullanıyoruz (Yine makale kuralı)
        # Genişletilmiş veriyi tekrar 768'e daraltır
        self.linear2 = nn.Linear(ff_hidden_size, hidden_size)

    def forward(self, x):
        x = self.gelu(self.linear1(x))
        return self.linear2(x)

# ==========================================
# ADIM 8: Encoder Block (Tek Bir Transformer Makinesi)
# ==========================================
# Attention ve FeedForward'ı birleştirir ve aralarına LayerNorm/Dropout ekler.
class EncoderBlock(nn.Module):
    def __init__(self, hidden_size=768, num_heads=12):
        super().__init__()
        self.attention = MultiHeadAttention(hidden_size, num_heads)
        self.norm1 = nn.LayerNorm(hidden_size)
        self.dropout1 = nn.Dropout(0.1)

        self.feed_forward = FeedForward(hidden_size)
        self.norm2 = nn.LayerNorm(hidden_size)
        self.dropout2 = nn.Dropout(0.1)

    def forward(self, x):
        # 1. Kısım: Attention -> Dropout -> Residual(Kestirme) Ekleme -> Normalizasyon
        att_out = self.attention(x)
        x = self.norm1(x + self.dropout1(att_out)) # x + att_out mantığı (Skip Connection)

        # 2. Kısım: FeedForward -> Dropout -> Residual Ekleme -> Normalizasyon
        ff_out = self.feed_forward(x)
        x = self.norm2(x + self.dropout2(ff_out))
        return x

# ==========================================
# ADIM 9: Ana BERT Modeli Sınıfı (Büyük Birleştirme)
# ==========================================
class BERTClassifier(nn.Module):
    # num_layers=2 yapıyoruz. (Makaledeki BERT-Base 12'dir ama GPU yanmasın diye ödevde 2 katman yeter)
    def __init__(self, vocab_size, max_len=32, hidden_size=768, num_heads=12, num_layers=2, num_classes=2):
        super().__init__()
        # 1. Giriş Kapısı (Önceden yazdığımız Embedding)
        self.embedding = BERTEmbedding(vocab_size, max_len, hidden_size)

        # 2. Encoder Bloklarını Alt Alta Diziyoruz (ModuleList ile)
        self.encoder_blocks = nn.ModuleList([
            EncoderBlock(hidden_size, num_heads) for _ in range(num_layers)
        ])

        # 3. Sınıflandırma Kafası (Spam mi Değil mi?)
        # Modelden çıkan 768 boyutu alıp, num_classes (2) boyutuna düşürür.
        self.classifier = nn.Linear(hidden_size, num_classes)

    def forward(self, input_ids, segment_ids):
        # Kelimeleri vektöre çevir
        x = self.embedding(input_ids, segment_ids)

        # Vektörleri sırayla 2 adet Transformer bloğundan geçir
        for block in self.encoder_blocks:
            x = block(x)

        # SİHİRLİ NOKTA: Sadece [CLS] token'ının vektörünü alıyoruz.
        # [CLS] cümleye en başta (0. index) eklemiştik.
        # x'in boyutu [16, 32, 768]. Biz [16, 0, 768] olan yeri kesip alıyoruz.
        cls_output = x[:, 0, :]

        # CLS vektörünü sınıflandırıcıya sok ve spam(1)/normal(0) tahminini çıkar
        logits = self.classifier(cls_output)
        return logits


